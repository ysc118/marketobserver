import fs from 'node:fs/promises';
import {gzipSync, gunzipSync} from 'node:zlib';
import {open, seal, validateTeam} from './crypto.mjs';

const [catalogFile, updateFile, linkFile, outputFile] = process.argv.slice(2);
if (!outputFile) throw Error('Usage: merge-week <current encrypted catalog> <private weekly update> <team link file> <output encrypted catalog>');
const link = await fs.readFile(linkFile, 'utf8');
const team = validateTeam(link.match(/[?&]team=([A-Za-z0-9_-]{43})(?:\s|$|&)/)?.[1]);
const catalog = JSON.parse(gunzipSync(open(await fs.readFile(catalogFile), team, 'hkbeat-catalog-v1/')));
const update = JSON.parse(await fs.readFile(updateFile, 'utf8'));
if (!/^\d{4}-\d{2}-\d{2}$/.test(update.week) || update.reviewScope !== 'reviewed') throw Error('A reviewed weekly snapshot is required');
if (!Array.isArray(update.notes) || !update.notes.length || update.notes.some(n => !n.theme || !/^[a-f0-9]{24}$/i.test(n.id))) throw Error('Incomplete note classification');
if (update.originals?.week !== update.week || update.originals.notes.length !== update.notes.length) throw Error('Original note snapshot mismatch');
const libraryBefore = JSON.stringify(catalog.library);
const originalWeeks = catalog.xhs.weeks;
if (!Array.isArray(originalWeeks)) throw Error('Unexpected catalog schema');
catalog.xhs.weeks = originalWeeks.filter(w => w.end !== update.week);
catalog.xhs.weeks.push({end: update.week, notes: update.notes, reviewScope: update.reviewScope});
catalog.xhs.weeks.sort((a,b) => b.end.localeCompare(a.end));
catalog.xhs.search_index.daily = {...catalog.xhs.search_index.daily, ...update.search_index.daily};
catalog.xhs.search_index.weekly = {...catalog.xhs.search_index.weekly, ...update.search_index.weekly};
catalog.xhs.search_index.brands = [...new Set([...catalog.xhs.search_index.brands, ...update.search_index.brands])];
catalog.xhs.indexWeek = Object.keys(catalog.xhs.search_index.weekly).sort().at(-1);
catalog.notes[update.week] = update.originals;
if (JSON.stringify(catalog.library) !== libraryBefore) throw Error('Drafts must not enter the team report archive');
const bytes = seal(gzipSync(JSON.stringify(catalog)), team, 'hkbeat-catalog-v1/');
const verified = JSON.parse(gunzipSync(open(bytes, team, 'hkbeat-catalog-v1/')));
const week = verified.xhs.weeks.find(w => w.end === update.week);
if (week.notes.length !== update.notes.length || verified.notes[update.week].notes.length !== update.notes.length) throw Error('Encrypted roundtrip verification failed');
await fs.writeFile(outputFile, bytes);
console.log(JSON.stringify({week:update.week, records:week.notes.length, related:week.notes.filter(n => n.theme !== '不相关').length, searchThrough:Object.keys(verified.xhs.search_index.daily).sort().at(-1), draftPublished:false}));
